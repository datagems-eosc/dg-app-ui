import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import type { FilePreviewData } from "@/types/filePreview";
import FilePreview from "./FilePreview";

vi.mock("next/dynamic", () => ({ default: () => () => null }));
it.each(["tabular", "json"] as const)(
  "does not offer a fabricated %s download",
  (type) => {
    render(
      <FilePreview
        fileData={
          type === "json"
            ? {
                type,
                filename: "data.json",
                fileSize: "",
                description: "",
                keywords: [],
                content: "{}",
              }
            : {
                type,
                filename: "data.csv",
                fileSize: "",
                description: "",
                columns: [],
                rows: [],
                totalRows: 0,
                statistics: [],
                dataQuality: { status: "unavailable" },
              }
        }
      />,
    );
    expect(
      screen.queryByRole("button", { name: /download/i }),
    ).not.toBeInTheDocument();
  },
);

it("shows only the current file's metrics and quality report after selection changes", async () => {
  const user = userEvent.setup();
  const first: FilePreviewData = {
    type: "tabular",
    filename: "first.csv",
    fileSize: "",
    description: "",
    rows: [],
    columns: [
      {
        id: "price",
        name: "Price",
        type: "numeric",
        visible: true,
        inferredSemanticType: "rental price",
      },
    ],
    statistics: [{ columnId: "price", mean: 91 }],
    dataQuality: {
      status: "available",
      summary: "First file report",
      findings: [],
    },
  };
  const { rerender } = render(<FilePreview fileData={first} />);
  await user.click(screen.getByRole("tab", { name: "Statistics" }));
  expect(screen.getByText("91")).toBeInTheDocument();
  expect(
    screen.getByText("Inferred semantic type: rental price"),
  ).toBeInTheDocument();
  await user.click(screen.getByRole("tab", { name: /Data Quality.*AI/ }));
  expect(screen.getByText("First file report")).toBeInTheDocument();
  expect(screen.getByText("Generated by the profiler")).toBeInTheDocument();
  rerender(
    <FilePreview
      fileData={{
        ...first,
        filename: "second.csv",
        columns: [{ ...first.columns[0], inferredSemanticType: undefined }],
        statistics: [{ columnId: "price", mean: 52 }],
        dataQuality: { status: "unavailable" },
      }}
    />,
  );
  await user.click(screen.getByRole("tab", { name: "Statistics" }));
  expect(screen.getByText("52")).toBeInTheDocument();
  expect(screen.queryByText("91")).not.toBeInTheDocument();
  expect(screen.queryByText(/inferred semantic type/i)).not.toBeInTheDocument();
  await user.click(screen.getByRole("tab", { name: "Data Quality" }));
  expect(
    screen.getByText("No data quality report available."),
  ).toBeInTheDocument();
  expect(screen.queryByText("First file report")).not.toBeInTheDocument();
  expect(
    screen.queryByText("Generated by the profiler"),
  ).not.toBeInTheDocument();
});
